# SENTINEL-M local installer (Phase 7).
# Developer/local deployment: installs dependencies, generates .env with a real
# secret key + seed admin password, initializes the database, and runs a
# self-check. NOT a GUI installer — packaging (PyInstaller/Electron) is not part
# of this build and is honestly listed as remaining work.
#
# Usage:  powershell -ExecutionPolicy Bypass -File scripts\install.ps1
param(
    [string]$Root = (Split-Path -Parent $PSScriptRoot),
    [switch]$SkipFrontend
)
$ErrorActionPreference = "Stop"

function New-Secret([int]$bytes = 32) {
    $b = New-Object byte[] $bytes
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
    return [Convert]::ToBase64String($b)
}

$backend = Join-Path $Root "backend\"
$frontend = Join-Path $Root "frontend\"

Write-Host "SENTINEL-M installer — root: $Root"

# 1. Python dependencies (backend)
Write-Host "  installing backend dependencies…"
python -m pip install --quiet --disable-pip-version-check -r (Join-Path $backend "requirements.txt")
if ($LASTEXITCODE -ne 0) { throw "backend dependency install failed" }

# 2. .env generation (idempotent: never overwrites an existing .env)
$envFile = Join-Path $backend ".env"
if (Test-Path $envFile) {
    Write-Host "  .env already present — keeping existing configuration"
} else {
    $seed = New-Secret 12
    $key = New-Secret 32
    @(
        "# Generated by scripts\install.ps1 — keep this file private.",
        "SENTINEL_SECRET_KEY=$key",
        "# First-boot admin password (change after first login; empty = random, printed once)",
        "SENTINEL_SEED_ADMIN_PASSWORD=$seed",
        "# Honeypot listeners bind here by default (loopback isolation)",
        "SENTINEL_DECEPTION_BIND=127.0.0.1",
        "# Emergency stop for real response actions",
        "SENTINEL_RESPONSE_ENABLED=true"
    ) | Set-Content -Path $envFile -Encoding utf8
    Write-Host "  wrote .env (secret key + seed admin password generated)"
}

# 3. Frontend build (unless skipped)
if (-not $SkipFrontend) {
    Write-Host "  installing frontend dependencies + building…"
    Push-Location $frontend
    try {
        npm install --silent
        if ($LASTEXITCODE -ne 0) { throw "npm install failed" }
        npm run build
        if ($LASTEXITCODE -ne 0) { throw "frontend build failed" }
    } finally { Pop-Location }
}

# 4. Database initialization + self-check (same sequence as server lifespan:
#    additive migrations → create_all → seed admin → STIX feed load → HTTP self-check)
Write-Host "  initializing database + running self-check…"
$check = @'
from app.main import _run_migrations, create_app
from app.core.config import settings
from app.core.database import Base, engine, SessionLocal
from app.intelligence.engine import intelligence_engine
from app.services.seed import seed_if_empty
from fastapi.testclient import TestClient

migrated = _run_migrations()
Base.metadata.create_all(bind=engine)
seeded = seed_if_empty()
feeds = intelligence_engine.load_feeds(SessionLocal())
app = create_app()
with TestClient(app) as client:
    root = client.get("/api/v1")
    assert root.status_code == 200, root.text
    login = client.post("/api/v1/auth/login",
                        json={"username": "admin", "password": settings.seed_admin_password})
    if login.status_code == 200:
        token = login.json()["access_token"]
        health = client.get("/api/v1/health", headers={"Authorization": f"Bearer {token}"})
        assert health.status_code == 200, health.text
        authed = f"health_ok modules={len(health.json()['modules'])}"
    else:
        authed = "health_skip (existing admin password; routing verified)"
print(f"OK root={root.json()['status']} {authed} migrations={migrated} seeded={seeded}")
'@
Push-Location $backend
try { $check | Out-File -FilePath _init_check.py -Encoding utf8; python _init_check.py; Remove-Item _init_check.py -Force } finally { Pop-Location }

Write-Host ""
Write-Host "Install complete."
Write-Host "  start backend : cd backend; python -m uvicorn app.main:app --port 8000"
Write-Host "  (8000 may be blocked on some Windows hosts — pick a free port, e.g. 8942)"
Write-Host "  serve frontend: cd frontend; npm run preview   (or npm run dev)"
Write-Host "  log in with the seed admin password from backend/.env, then change it."